"""Mitsuba reference rendering for general VOF-derived water meshes.

The mesh winding and geometric normals point from water toward air.  Mitsuba
uses that orientation to distinguish the exterior air from a homogeneous
absorbing interior medium.  Its smooth dielectric BSDF supplies Fresnel and
Snell at every intersection, while the medium applies Beer--Lambert
attenuation to each actual segment travelled in water.  Closed folds can
therefore enter, exit, and re-enter water without a height-field special case.

This is the offline reference path, not an extension of ``render_fast``.
Production scenes consume the beach and boulder meshes generated by the same
``SceneGeometry`` primitives as the flow solver.  ``ReceiverPlane`` remains
only for controlled analytic optical comparisons.

The height-field renderer's small constant upwelling ``scatter`` radiance is
not painted into this path.  The first mesh medium is explicitly clear and
purely absorbing; adding real participating-media scattering remains a named
closure if later images show that it is needed.

Passive foam and solid wetness are bounded vertex attributes.  They blend
declared material classes without moving geometry, adding procedural coverage,
or feeding anything back to the flow state.

Unresolved ripples reuse the existing periodic WKB closure as a tangent-space
normal map.  The map changes only the dielectric shading frame: triangle
winding still owns the water-medium boundary, and the extracted vertices still
own the silhouette.  Stable resolved normals suppress the map on steep and
overturned breaker faces; the existing foam blend suppresses it on covered
water.
"""

